const slide = (
  id: string,
  chapter: number,
  section: string,
  title: string,
  layout: TutorialSlideLayout,
  sourceText: string,
  notesVi: string[],
  methods: TutorialMethod[],
  codeBlocks: string[] = [],
  notesEn = notesVi,
): TutorialSlide => ({
  id,
  chapter,
  section,
  title,
  layout,
  sourceText,
  codeBlocks,
  methods,
  notes: { vi: notesVi, en: notesEn },
});

const chapter = (chapterNumber: number, title: string, slides: TutorialSlide[]): TutorialChapter => ({
  id: `curated_chapter_${String(chapterNumber).padStart(2, '0')}`,
  chapter: chapterNumber,
  title,
  sections: slides.map((item) => `${item.section} ${item.title}`),
  slides,
});

const chapterEssence = (chapterNumber: number, title: string, focus: string, methods: TutorialMethod[]) =>
  slide(
    `c${chapterNumber}_essence`,
    chapterNumber,
    `Chapter ${chapterNumber}`,
    title,
    'overview',
    focus,
    [
      'Nắm mental model trước khi nhớ cú pháp: request đi qua router, controller, model, view và test.',
      'Ưu tiên hiểu boundary: browser chỉ gửi request; Rails xử lý state; database giữ dữ liệu bền vững.',
      'Khi đọc code Rails, luôn hỏi: object nào nhận message, lifecycle nào đang chạy, failure path ở đâu.',
    ],
    methods,
  );

